def continent_name(code: str | None) -> str:
    """Full continent name for a two-letter code, or the text unchanged."""
    text = (code or "").strip()
    if not text:
        return ""
    return _CONTINENT.get(text.upper(), text)


def entity_name(number) -> str:
    """Entity name for an ADIF DXCC number, or '' when the number is unknown."""
    try:
        num = int(str(number).strip())
    except (TypeError, ValueError):
        return ""
    row = _ENTITIES.get(num)
    if not row:
        return ""
    return row[0]


def lookup(call: str | None, *, cty=None) -> str | None:
    """Entity name for ``call``, or None.

    Pass the loaded country file as ``cty`` so this matches the checklist.
    Without it, the builtin prefix list below is used. Unknown calls return
    None so the caller can leave the field blank.
    """
    if cty is not None:
        return cty.entity_name(call)
    found = describe(call)
    if not found:
        return None
    return found["name"] or None


def describe(call: str | None) -> dict | None:
    """Entity for ``call``, or None when the prefix is not known.

    Keys: ``number``, ``name``, ``continent`` (NA/SA/EU/AF/AS/OC/AN or ''),
    ``cq`` (int or None).
    """
    norm = _normalize(call)
    if not norm or not any(ch.isdigit() for ch in norm):
        return None
    body = location_body(norm)
    number = _structural_number(norm)
    if number is None:
        number = _compound_number(norm)
    if number is None:
        number = _match_number(body)
    if number is None:
        return None
    number = _adjust(number, body)
    return _pack(number, body)


def country_fields(call: str | None, *, cty=None, grid: str | None = None) -> dict:
    """Roster / decode fields. Unknown calls are blank, not an error.

    ``cty`` is the country file the checklist already uses. ``grid`` fills
    a CQ zone when that entity spans more than one zone.
    """
    if cty is not None:
        return cty.country_fields(call, grid)
    found = describe(call)
    if not found:
        return {"country": "", "continent": "", "cq_zone": None}
    return {
        "country": found["name"],
        "continent": found["continent"],
        "cq_zone": found["cq"],
    }


def _pack(number: int, body: str) -> dict | None:
    row = _ENTITIES.get(number)
    if not row:
        return None
    name, continent, cq = row
    if not name:
        return None
    if number == _US:
        cq = _call_area_cq(body, _US_CQ, cq)
    elif number == _CANADA:
        cq = _call_area_cq(body, _VE_CQ, cq)
    return {
        "number": number,
        "name": name,
        "continent": continent or "",
        "cq": cq,
    }


# Structural keys that are not already a builtin prefix or compound.
_ISLAND_NUM = {
    "SV/A": 180,
    "3Y/B": 24,
    "3Y/P": 199,
    "VP8/G": 235,
    "VP8/H": 241,
    "VP8/O": 238,
    "VP8/S": 240,
    "CE0X": 217,
    "CE0Y": 47,
    "CE0Z": 125,
    "CE0I": 125,
}


def _compound_number(norm: str) -> int | None:
    parts = [p for p in norm.split("/") if p]
    if len(parts) < 2:
        return None
    for size in (3, 2):
        if len(parts) < size:
            continue
        for i in range(len(parts) - size + 1):
            key = "/".join(parts[i:i + size])
            if key in _COMPOUND:
                return _COMPOUND[key]
    return None


def _structural_number(norm: str) -> int | None:
    key = island_key(norm)
    if not key:
        return None
    if key in _ISLAND_NUM:
        return _ISLAND_NUM[key]
    if key in _COMPOUND:
        return _COMPOUND[key]
    return _PREFIX.get(key)


def _match_number(token: str) -> int | None:
    if not token:
        return None
    for n in range(len(token), 0, -1):
        hit = _PREFIX.get(token[:n])
        if hit is not None:
            return hit
    return None


def _adjust(number: int, body: str) -> int:
    if kc4_antarctica(body):
        return 13
    kind = kg4_kind(body)
    if kind == "us" and number == _GTMO:
        return _US
    if kind == "gtmo" and number == _US:
        return _GTMO
    if number in (_EUROPE_RU, _ASIATIC_RU):
        digit = _first_digit(body)
        if digit in (0, 8, 9):
            return _ASIATIC_RU
        return _EUROPE_RU
    return number


def _first_digit(text: str) -> int | None:
    for ch in text:
        if ch.isdigit():
            return int(ch)
    return None


def _call_area_cq(body: str, table: dict, default):
    digit = _first_digit(body)
    if digit is None:
        return default
    return table.get(digit, default)


